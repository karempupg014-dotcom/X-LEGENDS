export function t(lang: Language, key: keyof typeof translations['ar'], params?: Record<string, string | number>): string {
  const dict = translations[lang] || translations.ar;
  let str = (dict[key] as string) || (translations.ar[key] as string) || key;
  if (params) {
    Object.entries(params).forEach(([pKey, pVal]) => {
      str = str.replace(new RegExp(`\\{${pKey}\\}`, 'g'), String(pVal));
    });
  }
  return str;
}
